"""The storage interface the simulation depends on.

Simulation logic (pipelines, scenarios, validators) talks to this ``Protocol``
only. ``app.db.repository.SqlRepository`` implements it against SQL Server; the
unit tests use an in-memory implementation so the logic is tested without a
database. Rows are plain dicts so neither side leaks ORM objects.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Any, Protocol

Row = dict[str, Any]


class SimRepository(Protocol):
    # --- baseline / state
    def get_state(self) -> Row | None: ...
    def set_sim_now(self, when: datetime) -> None: ...
    def is_empty(self) -> bool: ...
    def seed(self, data: Any) -> None: ...
    def table_counts(self) -> dict[str, int]: ...
    def integrity_problems(self) -> list[str]: ...
    def tagged_row_counts(self) -> dict[str, int]: ...
    def wipe(self) -> dict[str, int]: ...

    # --- definitions, runs, incidents, validations
    def list_pipelines(self) -> list[Row]: ...
    def get_pipeline(self, pipeline_id: str) -> Row | None: ...
    def list_runs(self, pipeline_id: str | None = None, limit: int = 20) -> list[Row]: ...
    def get_run(self, run_id: str) -> Row | None: ...
    def run_exists(self, run_id: str) -> bool: ...
    def latest_successful_run(self, pipeline_id: str) -> Row | None: ...
    def save_run(self, run: Row, validations: list[Row], incident: Row | None) -> None: ...
    def next_incident_id(self) -> str: ...
    def list_incidents(self, limit: int = 20) -> list[Row]: ...
    def get_validations(self, run_id: str) -> list[Row]: ...

    # --- data the pipelines read / write
    def get_feed_rows(self, batch_date: date) -> list[Row]: ...
    def known_event_ids(self, event_ids: list[str]) -> set[str]: ...
    def insert_orders(self, orders: list[Row]) -> int: ...
    def order_summary(self, batch_date: date) -> Row: ...
    def duplicate_events(self) -> list[Row]: ...
    def order_total_mismatches(self) -> list[Row]: ...
    def future_dated_orders(self, now: datetime) -> list[Row]: ...
    def sample_orders(self, limit: int) -> list[Row]: ...
    def observed_schema(self, table_name: str) -> dict[str, str]: ...

    # --- scenarios
    def get_scenarios(self) -> dict[str, Row]: ...
    def save_scenario(self, row: Row) -> None: ...
    def delete_scenario_rows(self, scenario_id: str) -> int: ...
